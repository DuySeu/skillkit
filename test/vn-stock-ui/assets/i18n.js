/* Values that must be re-formatted when the locale changes (1.284,56 vs 1,284.56).
   Any element with data-num="<raw>" data-dec="<n>" is re-rendered on switch. */
window.I18N = I18N;
window.getLang = () => document.documentElement.getAttribute('lang') || 'vi';

window.t = function (key) {
  const lang = window.getLang();
  return (I18N[lang] && I18N[lang][key]) ?? I18N.vi[key] ?? key;
};

window.applyI18n = function (lang) {
  const dict = I18N[lang] || I18N.vi;
  document.documentElement.setAttribute('lang', lang);

  const set = (attr, fn) => {
    document.querySelectorAll(`[${attr}]`).forEach((el) => {
      const v = dict[el.getAttribute(attr)];
      if (v != null) fn(el, v);
    });
  };

  set('data-i18n', (el, v) => { el.textContent = v; });
  set('data-i18n-html', (el, v) => { el.innerHTML = v; });
  set('data-i18n-ph', (el, v) => { el.setAttribute('placeholder', v); });
  set('data-i18n-label', (el, v) => { el.setAttribute('aria-label', v); });
  set('data-i18n-title', (el, v) => { el.setAttribute('title', v); });

  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
};
